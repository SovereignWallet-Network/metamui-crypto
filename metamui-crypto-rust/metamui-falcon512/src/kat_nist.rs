#[cfg(test)]
mod tests {
    use super::*;
    
    #[test]
    fn test_kat_generation() {
        // Generate a few test vectors
        let vectors = generate_kat_vectors(3).unwrap();
        assert_eq!(vectors.len(), 3);
        
        // Check vectors have expected structure
        for (i, vec) in vectors.iter().enumerate() {
            assert_eq!(vec.count, i);
            assert_eq!(vec.seed.len(), 48);
            assert_eq!(vec.msg.len(), vec.mlen);
            assert_eq!(vec.pk.len(), crate::constants::PUBLIC_KEY_SIZE);
            // sk.to_bytes() uses NIST reference format (1281 bytes: f:6bit + g:6bit + F:8bit)
            assert_eq!(vec.sk.len(), 1281);
            assert_eq!(vec.sm.len(), vec.smlen);
        }
    }
    
    #[test]
    fn test_loading_unavailable_official_vectors_fails_closed() {
        assert!(matches!(
            load_nist_kat_vectors(),
            Err(Falcon512Error::NotImplemented)
        ));
    }

    #[test]
    fn test_entropy_seed_generation() {
        let initial = [0u8; 48];
        let seed1 = generate_entropy_seed(0, &initial);
        let seed2 = generate_entropy_seed(1, &seed1);
        
        // Seeds should be different
        assert_ne!(seed1, seed2);
        
        // Seeds should be deterministic
        let seed1_again = generate_entropy_seed(0, &initial);
        assert_eq!(seed1, seed1_again);
    }
    
    #[test]
    fn test_seed_update() {
        let mut seed = [0u8; 48];
        let entropy = [0xFFu8; 48];
        
        update_seed(&mut seed, &entropy);
        
        // Should have XORed and incremented (big-endian)
        // Starting with all 0x00, XOR with 0xFF gives all 0xFF
        // Incrementing 0xFFFFFF...FFFF by 1 gives 0x000000...0000 (overflow)
        for i in 0..48 {
            assert_eq!(seed[i], 0x00, "seed[{}] should be 0x00 after overflow", i);
        }
    }
}
